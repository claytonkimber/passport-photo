// Builds the country pages, the landing page's country list and sitemap.xml from specs.js.
// Run it after editing specs.js:   node tools/build-site.mjs
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SITE = "https://claytonkimber.github.io/passport-photo/";   // change here if the site moves to its own domain
const CHECKED = "November 2026";                                   // when the rules were last verified
const MARK = "<!-- generated by tools/build-site.mjs -->";
const { SPECS } = await import(pathToFileURL(path.join(ROOT, "specs.js")).href);

const SHORT = { US: "US", GB: "UK" };
const MEASURE = { hair: "chin to top of hair", skull: "chin to top of head, not counting hair", hairline: "chin to hairline" };
const esc = s => String(s).replace(/[&<>"]/g, c => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" }[c]));
const mm = v => String(Math.round(v * 10) / 10);
const range = (a, b) => a === b ? `${mm(a)} mm` : `${mm(a)}–${mm(b)} mm`;
const slugOf = s => s.name.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
const list = a => a.length < 2 ? a.join("") : `${a.slice(0, -1).join(", ")} or ${a[a.length - 1]}`;
const size = s => Math.abs(s.w_mm - 50.8) < 0.6 && Math.abs(s.h_mm - 50.8) < 0.6 ? "2×2 in (51×51 mm)" : `${mm(s.w_mm)}×${mm(s.h_mm)} mm`;

const header = `<header class="site">
  <div class="wrap">
    <a class="brand" href="../"><img src="../icons/icon.svg" alt="" width="32" height="32">Passport Photo</a>
    <nav class="site" aria-label="Sections">
      <a href="../#countries">All countries</a>
      <a href="../#install">Install</a>
      <a href="../#faq">FAQ</a>
    </nav>
  </div>
</header>`;

const footer = `<footer class="site">
  <div class="wrap">
    <span>© 2026 Clayton Kimber · <a href="https://github.com/claytonkimber/passport-photo/blob/main/LICENSE">MIT license</a></span>
    <a href="https://github.com/claytonkimber/passport-photo">Source code</a>
    <a href="https://github.com/claytonkimber/passport-photo/issues/new">Report a bug</a>
    <a href="../#disclaimer">Disclaimer</a>
  </div>
</footer>`;

function countryPage(code, s) {
  const short = SHORT[code] || s.name, url = `${SITE}${slugOf(s)}/`, bg = list(s.bg);
  const title = `${short} Passport Photo at Home, Free (${size(s)}) | Passport Photo`;
  const desc = `Take a ${short} passport photo at home for free: ${size(s)}, plain ${bg} background. Live guides and official-rule checks; your photo never leaves your phone.`;
  const rows = [
    ["Photo size", size(s)],
    ["Head height", `${range(s.head_min_mm, s.head_max_mm)}, measured ${MEASURE[s.head_measure || "hair"]}`],
    s.eye_min_mm != null && ["Eye line", `${range(s.eye_min_mm, s.eye_max_mm)} from the bottom of the photo`],
    s.top_min_mm != null && ["Space above head", range(s.top_min_mm, s.top_max_mm)],
    ["Background", `Plain ${bg}`],
    s.digital_px && ["Online upload", `At least ${s.digital_px.w}×${s.digital_px.h} pixels`],
    ["Glasses", s.glasses_allowed ? "Allowed in some cases (no glare or tint, eyes clearly visible). Removing them is safest."
                                  : "Remove them (exceptions are rare, such as medical reasons)."],
    s.notes && ["Notes", s.notes],
  ].filter(Boolean);
  const source = s.source ? `<a href="${esc(s.source)}">the official ${esc(short)} rules</a>` : `the official ${esc(short)} rules`;
  return `<!doctype html>
${MARK}
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
<title>${esc(title)}</title>
<meta name="description" content="${esc(desc)}">
<link rel="canonical" href="${url}">
<meta name="theme-color" content="#0b0f14">
<link rel="manifest" href="../manifest.webmanifest">
<link rel="icon" href="../icons/icon.svg" type="image/svg+xml">
<link rel="apple-touch-icon" href="../icons/apple-touch-icon.png">
<meta property="og:type" content="website">
<meta property="og:site_name" content="Passport Photo">
<meta property="og:title" content="${esc(`${short} passport photo at home, free`)}">
<meta property="og:description" content="${esc(desc)}">
<meta property="og:url" content="${url}">
<meta property="og:image" content="${SITE}og-image.png">
<meta name="twitter:card" content="summary_large_image">
<link rel="stylesheet" href="../site.css">
</head>
<body>

${header}

<main>
  <div class="wrap hero">
    <h1>${esc(short)} passport photo at home</h1>
    <p class="lead">Take a ${esc(short)} passport photo with your phone for free. The camera guides you to the official ${esc(size(s))} format with a plain ${esc(bg)} background, checks the result, and never uploads your photo.</p>
    <div class="cta">
      <a class="button primary" href="../app/?country=${code}">Open the camera for ${esc(short)} photos</a>
      <button class="button" type="button" data-install-button hidden>Install app</button>
    </div>
  </div>

  <section>
    <div class="wrap">
      <h2>${esc(short)} passport photo rules</h2>
      <dl class="rules">
${rows.map(([k, v]) => `        <dt>${esc(k)}</dt><dd>${esc(v)}</dd>`).join("\n")}
      </dl>
      <p class="note">Checked against ${source} in ${CHECKED}. Rules change, so check that page before you apply. The exact wording behind each value is in the <a href="https://github.com/claytonkimber/passport-photo/blob/main/evidence.json">evidence file</a>.</p>
    </div>
  </section>

  <section>
    <div class="wrap">
      <h2>Tips for a photo that passes</h2>
      <ul>
        <li>Stand about 60 cm (2 ft) in front of a plain, light wall, facing a window or soft light.</li>
        <li>Have someone else take it with the back camera from about 1.2 m (4 ft) away. Arm's-length selfies can distort your face.</li>
        <li>Keep a neutral face with your mouth closed and both eyes open, looking straight at the lens.</li>
        <li>Remove hats, headphones${s.glasses_allowed ? "" : ", glasses"} and anything covering your face.</li>
        <li>Use the saved JPEG for online applications, or print the 4×6 in (10×15 cm) sheet at 100% scale and cut along the lines.</li>
      </ul>
      <p class="cta"><a class="button primary" href="../app/?country=${code}">Open the camera</a></p>
    </div>
  </section>

  <section class="disclaimer">
    <div class="wrap">
      <p>This free tool is provided as is, with no warranty. It can make mistakes, so check your photo against the official rules before you submit it. Read the full <a href="../#disclaimer">disclaimer</a>.</p>
    </div>
  </section>
</main>

${footer}

<script src="../install.js"></script>
</body>
</html>
`;
}

const codes = Object.keys(SPECS).sort((a, b) => SPECS[a].name.localeCompare(SPECS[b].name));
const slugs = new Set(codes.map(c => slugOf(SPECS[c])));

// Remove pages for countries that are no longer supported (only folders this script made).
for (const d of fs.readdirSync(ROOT, { withFileTypes: true })) {
  const page = path.join(ROOT, d.name, "index.html");
  if (d.isDirectory() && !slugs.has(d.name) && fs.existsSync(page) && fs.readFileSync(page, "utf8").includes(MARK)) {
    fs.rmSync(path.join(ROOT, d.name), { recursive: true });
    console.log("removed", d.name);
  }
}

for (const c of codes) {
  const dir = path.join(ROOT, slugOf(SPECS[c]));
  fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(path.join(dir, "index.html"), countryPage(c, SPECS[c]));
}

const landingPath = path.join(ROOT, "index.html");
const cards = codes.map(c => {
  const s = SPECS[c];
  return `        <a href="${slugOf(s)}/"><b>${esc(s.name)}</b><small>${esc(size(s))}, ${esc(list(s.bg))} background</small></a>`;
}).join("\n");
const landing = fs.readFileSync(landingPath, "utf8")
  .replace(/<!--COUNTRIES-->[\s\S]*?<!--\/COUNTRIES-->/, `<!--COUNTRIES-->\n${cards}\n<!--/COUNTRIES-->`)
  .replace(/<!--COUNT-->[\s\S]*?<!--\/COUNT-->/, `<!--COUNT-->${codes.length}<!--/COUNT-->`);
fs.writeFileSync(landingPath, landing);

const today = new Date().toISOString().slice(0, 10);
const urls = ["", "app/", ...codes.map(c => `${slugOf(SPECS[c])}/`)];
fs.writeFileSync(path.join(ROOT, "sitemap.xml"), `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${urls.map(u => `  <url><loc>${SITE}${u}</loc><lastmod>${today}</lastmod></url>`).join("\n")}
</urlset>
`);

console.log(`built ${codes.length} country pages: ${codes.map(c => slugOf(SPECS[c])).join(", ")}`);
