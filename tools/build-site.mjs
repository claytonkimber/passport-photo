// Builds the country pages (English plus AI-assisted translations), the landing page's country list
// and sitemap.xml from specs.js and the text tables in tools/i18n/.
// Run it after editing specs.js or a text table:   node tools/build-site.mjs
import fs from "node:fs";
import path from "node:path";
import { execFileSync } from "node:child_process";
import { fileURLToPath, pathToFileURL } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const I18N = path.join(ROOT, "tools", "i18n");
const SITE = "https://claytonkimber.github.io/passport-photo/";   // change here if the site moves to its own domain
const GITHUB = "https://github.com/claytonkimber/passport-photo";
const MARK = "<!-- generated by tools/build-site.mjs -->";
const { SPECS } = await import(pathToFileURL(path.join(ROOT, "specs.js")).href);

// Countries whose people mostly search in another language get a translated page: text table per country.
const TRANSLATIONS = { JP: ["ja"], IT: ["it"], NL: ["nl"], PL: ["pl"], TW: ["zh-tw"], HK: ["zh-hk"] };
const SHORT = { US: "US", GB: "UK" };

const readTable = f => JSON.parse(fs.readFileSync(path.join(I18N, `${f}.json`), "utf8"));
const EN = readTable("en");
const esc = s => String(s).replace(/[&<>"]/g, c => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" }[c]));
const fill = (t, v) => String(t).replace(/\{(\w+)\}/g, (_, k) => v[k] ?? `{${k}}`);
const fillHtml = (t, html) => esc(t).replace(/\{(\w+)\}/g, (_, k) => html[k] ?? `{${k}}`);   // text escaped, values are HTML
const mm = v => String(Math.round(v * 10) / 10);
const range = (a, b) => a === b ? `${mm(a)} mm` : `${mm(a)}–${mm(b)} mm`;
const slugOf = s => s.name.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
const size = s => Math.abs(s.w_mm - 50.8) < 0.6 && Math.abs(s.h_mm - 50.8) < 0.6 ? "2×2 in (51×51 mm)" : `${mm(s.w_mm)}×${mm(s.h_mm)} mm`;
const colorList = (s, T) => new Intl.ListFormat(T.lang, { type: "disjunction" }).format(s.bg.map(c => T.colors[c] || c));

// Translation files that fail the checker are left out rather than published half-broken.
function usableTranslations(code) {
  return (TRANSLATIONS[code] || []).filter(f => {
    if (!fs.existsSync(path.join(I18N, `${f}.json`))) return false;
    try { execFileSync(process.execPath, [path.join(I18N, "check.mjs"), `${f}.json`], { stdio: "pipe" }); return true; }
    catch (e) { console.warn(`skipping ${f}.json:\n${e.stdout}`); return false; }
  });
}

function countryPage(code, s, T, page, versions) {
  const up = "../".repeat(page.depth), translated = T.lang !== "en";
  const short = T.short || SHORT[code] || s.name, sz = size(s), bg = colorList(s, T);
  const v = { short, size: sz, bg };
  const rows = [
    [T.rowSize, sz],
    [T.rowHead, fill(T.headValue, { range: range(s.head_min_mm, s.head_max_mm), measure: T.measure[s.head_measure || "hair"] })],
    s.eye_min_mm != null && [T.rowEye, fill(T.eyeValue, { range: range(s.eye_min_mm, s.eye_max_mm) })],
    s.top_min_mm != null && [T.rowTop, range(s.top_min_mm, s.top_max_mm)],
    [T.rowBg, fill(T.bgValue, { bg })],
    s.digital_px && [T.rowUpload, fill(T.uploadValue, { w: s.digital_px.w, h: s.digital_px.h })],
    [T.rowGlasses, s.glasses_allowed ? T.glassesYes : T.glassesNo],
    (T.notes || s.notes) && [T.rowNotes, T.notes || s.notes],
  ].filter(Boolean);
  const sourceText = esc(fill(T.sourceText, v));
  const checked = fillHtml(T.checked, {
    source: s.source ? `<a href="${esc(s.source)}">${sourceText}</a>` : sourceText,
    date: esc(T.date),
    evidence: `<a href="${GITHUB}/blob/main/evidence.json">${esc(T.evidenceText)}</a>`,
  });
  const english = versions.find(x => x.lang === "en");
  const alternates = versions.length > 1
    ? [...versions.map(x => `<link rel="alternate" hreflang="${x.lang}" href="${x.url}">`),
       `<link rel="alternate" hreflang="x-default" href="${english.url}">`].join("\n") : "";
  const others = versions.filter(x => x.lang !== T.lang);
  const switcher = others.length
    ? `<div class="wrap langs">${esc(T.otherLanguages)} ${others.map(x => `<a href="${up}${x.path}" lang="${x.lang}" hreflang="${x.lang}">${esc(x.langName)}</a>`).join(" ")}</div>` : "";
  const notice = translated ? `
<div class="wrap">
  <aside class="ai-notice" role="note">
    <p><b>${esc(T.aiNoticeTitle)}</b> ${esc(T.aiNotice)} ${esc(T.appInEnglish)} <a href="${up}${english.path}">${esc(T.englishLink)}</a></p>
    <p lang="en"><b>AI-assisted translation.</b> This page was translated with the help of AI and may contain mistakes. The English page is the reference, and the official government rules always take precedence. <a href="${up}${english.path}">Read this page in English</a>.</p>
  </aside>
</div>` : "";
  const tips = [T.tipLight, T.tipHelper, T.tipFace, s.glasses_allowed ? T.tipRemoveNoGlasses : T.tipRemoveGlasses, T.tipSave];
  const desc = fill(T.description, v);

  return `<!doctype html>
${MARK}
<html lang="${T.lang}">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
<title>${esc(fill(T.title, v))}</title>
<meta name="description" content="${esc(desc)}">
<link rel="canonical" href="${page.url}">
${alternates}
<meta name="theme-color" content="#0b0f14">
<link rel="manifest" href="${up}manifest.webmanifest">
<link rel="icon" href="${up}icons/icon.svg" type="image/svg+xml">
<link rel="apple-touch-icon" href="${up}icons/apple-touch-icon.png">
<meta property="og:type" content="website">
<meta property="og:site_name" content="Passport Photo">
<meta property="og:title" content="${esc(fill(T.ogTitle, v))}">
<meta property="og:description" content="${esc(desc)}">
<meta property="og:url" content="${page.url}">
<meta property="og:image" content="${SITE}og-image.png">
<meta name="twitter:card" content="summary_large_image">
<link rel="stylesheet" href="${up}site.css">
</head>
<body>

<header class="site">
  <div class="wrap">
    <a class="brand" href="${up}"><img src="${up}icons/icon.svg" alt="" width="32" height="32">Passport Photo</a>
    <nav class="site" aria-label="Sections">
      <a href="${up}#countries">${esc(T.navAll)}</a>
      <a href="${up}#install">${esc(T.navInstall)}</a>
      <a href="${up}#faq">${esc(T.navFaq)}</a>
    </nav>
  </div>
</header>
${notice}
${switcher}

<main>
  <div class="wrap hero">
    <h1>${esc(fill(T.h1, v))}</h1>
    <p class="lead">${esc(fill(T.lead, v))}</p>
    <div class="cta">
      <a class="button primary" href="${up}app/?country=${code}">${esc(fill(T.ctaCountry, v))}</a>
      <button class="button" type="button" data-install-button hidden>${esc(T.install)}</button>
    </div>
  </div>

  <section>
    <div class="wrap">
      <h2>${esc(fill(T.rulesHeading, v))}</h2>
      <dl class="rules">
${rows.map(([k, val]) => `        <dt>${esc(k)}</dt><dd>${esc(val)}</dd>`).join("\n")}
      </dl>
      <p class="note">${checked}</p>
    </div>
  </section>

  <section>
    <div class="wrap">
      <h2>${esc(T.tipsHeading)}</h2>
      <ul>
${tips.map(t => `        <li>${esc(t)}</li>`).join("\n")}
      </ul>
      <p class="cta"><a class="button primary" href="${up}app/?country=${code}">${esc(T.ctaOpen)}</a></p>
    </div>
  </section>

  <section class="disclaimer">
    <div class="wrap">
      <p>${fillHtml(T.disclaimerShort, { link: `<a href="${up}#disclaimer">${esc(T.disclaimerLink)}</a>` })}</p>
    </div>
  </section>
</main>

<footer class="site">
  <div class="wrap">
    <span>© 2026 Clayton Kimber · <a href="${GITHUB}/blob/main/LICENSE">${esc(T.footerLicense)}</a></span>
    <a href="${GITHUB}">${esc(T.footerSource)}</a>
    <a href="${GITHUB}/issues/new">${esc(T.footerBug)}</a>
    <a href="${up}#disclaimer">${esc(T.footerDisclaimer)}</a>
  </div>
</footer>

<script src="${up}install.js"></script>
</body>
</html>
`;
}

// Remove generated folders that are no longer wanted (only ones this script made).
function prune(dir, keep) {
  for (const d of fs.readdirSync(dir, { withFileTypes: true })) {
    const page = path.join(dir, d.name, "index.html");
    if (d.isDirectory() && !keep.has(d.name) && fs.existsSync(page) && fs.readFileSync(page, "utf8").includes(MARK)) {
      fs.rmSync(path.join(dir, d.name), { recursive: true });
      console.log("removed", path.relative(ROOT, path.join(dir, d.name)));
    }
  }
}

const codes = Object.keys(SPECS).sort((a, b) => SPECS[a].name.localeCompare(SPECS[b].name));
prune(ROOT, new Set(codes.map(c => slugOf(SPECS[c]))));

const sitemapUrls = ["", "app/"], cardLangs = {};
for (const c of codes) {
  const s = SPECS[c], slug = slugOf(s);
  const tables = [["en", EN], ...usableTranslations(c).map(f => [f, readTable(f)])];
  const versions = tables.map(([f, T]) => {
    const p = f === "en" ? `${slug}/` : `${slug}/${f}/`;
    return { file: f, T, lang: T.lang, langName: T.langName, path: p, url: SITE + p, depth: p.split("/").length - 1 };
  });
  prune(path.join(ROOT, slug), new Set(versions.filter(x => x.file !== "en").map(x => x.file)));
  for (const page of versions) {
    const dir = path.join(ROOT, page.path);
    fs.mkdirSync(dir, { recursive: true });
    fs.writeFileSync(path.join(dir, "index.html"), countryPage(c, s, page.T, page, versions));
    sitemapUrls.push(page.path);
  }
  cardLangs[c] = versions.filter(x => x.file !== "en").map(x => x.langName);
}

const landingPath = path.join(ROOT, "index.html");
const cards = codes.map(c => {
  const s = SPECS[c], langs = cardLangs[c].length ? ` · ${cardLangs[c].join(", ")}` : "";
  return `        <a href="${slugOf(s)}/"><b>${esc(s.name)}</b><small>${esc(size(s))}, ${esc(colorList(s, EN))} background${esc(langs)}</small></a>`;
}).join("\n");
const landing = fs.readFileSync(landingPath, "utf8")
  .replace(/<!--COUNTRIES-->[\s\S]*?<!--\/COUNTRIES-->/, `<!--COUNTRIES-->\n${cards}\n<!--/COUNTRIES-->`)
  .replace(/<!--COUNT-->[\s\S]*?<!--\/COUNT-->/, `<!--COUNT-->${codes.length}<!--/COUNT-->`);
fs.writeFileSync(landingPath, landing);

const today = new Date().toISOString().slice(0, 10);
fs.writeFileSync(path.join(ROOT, "sitemap.xml"), `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${sitemapUrls.map(u => `  <url><loc>${SITE}${u}</loc><lastmod>${today}</lastmod></url>`).join("\n")}
</urlset>
`);

const translated = Object.values(cardLangs).flat().length;
console.log(`built ${codes.length} English country pages and ${translated} translated pages; sitemap has ${sitemapUrls.length} URLs`);
